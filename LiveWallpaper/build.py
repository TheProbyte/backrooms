"""Builds wallpaper/assets.js from src/scene.png.

Outputs (all embedded as data URIs so the page works from file:// in Lively / Wallpaper Engine):
  base   - the photo
  masks  - R: bush sway, G: grass sway, B: the man
  sky    - sky openings (drives the light shafts)
  bloom  - blurred highlights, used for halation and the sun glow
Run:  python build.py   (writes wallpaper/assets.js and debug/ previews)
"""
import base64, io, os
import numpy as np
import cv2
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src", "scene.png")
OUT = os.path.join(HERE, "wallpaper", "assets.js")
DBG = os.path.join(HERE, "debug")

img = np.asarray(Image.open(SRC).convert("RGB")).astype(np.float32) / 255.0
H, W = img.shape[:2]
yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)


def poly_mask(points, blur=0):
    m = np.zeros((H, W), np.float32)
    cv2.fillPoly(m, [np.array(points, np.int32)], 1.0)
    if blur:
        m = cv2.GaussianBlur(m, (0, 0), blur)
    return m


def smoothstep(a, b, x):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


# The man, traced from the photo (pixel coords in the 1816x1014 source).
MAN = [(900, 510), (936, 518), (957, 545), (962, 585), (950, 614), (976, 627), (1001, 660),
       (1016, 700), (1031, 733), (1052, 754), (1060, 776), (1052, 807), (1012, 837), (976, 862),
       (920, 882), (838, 882), (806, 866), (803, 800), (794, 750), (794, 690), (803, 643),
       (828, 620), (853, 611), (848, 580), (850, 540), (868, 518)]

# Trunks that reach down into the bushes/grass: these must not ripple with the plants.
TRUNKS = [
    [(195, 0), (305, 0), (310, 450), (330, 650), (348, 772), (188, 777), (200, 450)],
    [(398, 0), (497, 0), (495, 580), (507, 637), (393, 637)],
    [(1170, 0), (1300, 0), (1296, 450), (1307, 702), (1118, 707), (1155, 600), (1172, 450)],
    [(1333, 0), (1403, 0), (1405, 622), (1328, 622)],
    [(1545, 0), (1640, 0), (1642, 642), (1538, 642)],
    [(98, 0), (157, 0), (157, 585), (98, 585)],
    [(541, 0), (597, 0), (597, 475), (541, 475)],
    [(698, 0), (762, 0), (762, 465), (698, 465)],
    [(998, 0), (1037, 0), (1037, 445), (998, 445)],
    [(1700, 0), (1787, 0), (1787, 605), (1700, 605)],
]

man = poly_mask(MAN, blur=3)
man_hard = poly_mask(MAN)
trunks = np.zeros((H, W), np.float32)
for t in TRUNKS:
    trunks = np.maximum(trunks, poly_mask(t))
trunks = cv2.GaussianBlur(trunks, (0, 0), 6)

# Keep plant motion off the man with a soft margin so nothing tears at his outline.
man_keepout = cv2.GaussianBlur(cv2.dilate(man_hard, np.ones((9, 9), np.uint8)), (0, 0), 6)
free = (1 - trunks) * (1 - man_keepout)

lum = img.max(axis=2)
green = smoothstep(0.0, 0.06, img[..., 1] - np.maximum(img[..., 0], img[..., 2]) * 0.85)
green = cv2.GaussianBlur(green, (0, 0), 5)

bush = smoothstep(420, 520, yy) * (1 - smoothstep(700, 820, yy))
bush = bush * (0.45 + 0.55 * green) * free
grass = smoothstep(600, 760, yy) * (0.6 + 0.4 * smoothstep(760, 1014, yy)) * free

sky = smoothstep(0.22, 0.5, lum) * (1 - smoothstep(420, 470, yy))
sky = np.maximum(sky, 0)

masks = np.dstack([bush, grass, man])
masks = np.clip(masks * 255 + 0.5, 0, 255).astype(np.uint8)

# Halation / glow map: highlights blurred at two radii.
hi = np.clip(img - 0.42, 0, None) * smoothstep(0.42, 0.75, lum)[..., None]
bloom = cv2.GaussianBlur(hi, (0, 0), 7) * 1.6 + cv2.GaussianBlur(hi, (0, 0), 34) * 2.4
bloom = np.clip(bloom / max(bloom.max(), 1e-4), 0, 1)
bloom_small = cv2.resize(bloom, (W // 2, H // 2), interpolation=cv2.INTER_AREA)


def data_uri(arr_u8, fmt, **kw):
    buf = io.BytesIO()
    mode = "L" if arr_u8.ndim == 2 else "RGB"
    Image.fromarray(arr_u8, mode).save(buf, fmt, **kw)
    mime = "image/png" if fmt == "PNG" else "image/jpeg"
    return f"data:{mime};base64," + base64.b64encode(buf.getvalue()).decode()


# Strip the photo's own (frozen) grain so the animated grain can replace it.
base_u8 = np.asarray(Image.open(SRC).convert("RGB"))
base_u8 = cv2.fastNlMeansDenoisingColored(base_u8, None, 4, 5, 7, 21)
sky_u8 = (np.clip(cv2.GaussianBlur(sky, (0, 0), 1.5), 0, 1) * 255 + 0.5).astype(np.uint8)

bloom_u8 = (bloom_small * 255 + 0.5).astype(np.uint8)

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("// Generated by build.py - do not edit by hand.\n")
    f.write(f"window.SCENE = {{ width: {W}, height: {H}, sun: [{905 / W:.4f}, {362 / H:.4f}] }};\n")
    f.write("window.ASSETS = {\n")
    f.write(f'  base: "{data_uri(base_u8, "JPEG", quality=95, subsampling=0)}",\n')
    f.write(f'  masks: "{data_uri(masks, "PNG", optimize=True)}",\n')
    f.write(f'  sky: "{data_uri(sky_u8, "PNG", optimize=True)}",\n')
    f.write(f'  bloom: "{data_uri(bloom_u8, "JPEG", quality=92)}"\n')
    f.write("};\n")

os.makedirs(DBG, exist_ok=True)
Image.fromarray(masks).save(os.path.join(DBG, "masks_rgb.png"))
Image.fromarray(sky_u8).save(os.path.join(DBG, "mask_sky.png"))
Image.fromarray(base_u8).save(os.path.join(DBG, "base_denoised.png"))
Image.fromarray(bloom_u8).save(os.path.join(DBG, "bloom.png"))
print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB")
